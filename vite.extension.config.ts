import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import * as esbuild from 'esbuild';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { build as viteBuild, defineConfig, Plugin } from 'vite';

const rootDir = path.dirname(fileURLToPath(import.meta.url));
const distExtensionDir = path.resolve(rootDir, 'dist-extension');

/**
 * Manifest V3 Bundler Plugin
 * Produces complete dist-extension/ output meeting all SRS Phase-2 constraints:
 * - Content script: ONE self-contained IIFE bundle with CSS inlined via ?inline
 * - Background: ES-module service worker
 * - HTML entries: popup.html, options.html, onboarding.html
 * - Fonts: bundled as woff2 in fonts/
 * - Manifest: permissions activeTab, scripting, storage ONLY; host_permissions backend origin ONLY
 */
function manifestV3Plugin(): Plugin {
  return {
    name: 'formassist-manifest-v3-plugin',
    async closeBundle() {
      console.log('⚡ Generating Manifest V3 extension artifacts in dist-extension/...');

      // 1. Bundle Background Service Worker as ES Module
      const bgOutDir = path.join(distExtensionDir, 'background');
      fs.mkdirSync(bgOutDir, { recursive: true });
      await esbuild.build({
        entryPoints: [path.join(rootDir, 'extension/background/service-worker.ts')],
        outfile: path.join(bgOutDir, 'service-worker.js'),
        bundle: true,
        format: 'esm',
        target: 'es2022',
        platform: 'browser',
        minify: false,
        sourcemap: false,
      });

      // 2. Bundle Content Script as ONE self-contained IIFE bundle (classic script, no ES imports)
      const contentOutDir = path.join(distExtensionDir, 'content');
      fs.mkdirSync(contentOutDir, { recursive: true });

      await viteBuild({
        configFile: false,
        plugins: [react(), tailwindcss()],
        resolve: {
          alias: {
            '@': rootDir,
          },
        },
        define: {
          'process.env.NODE_ENV': '"production"',
        },
        build: {
          outDir: contentOutDir,
          emptyOutDir: false,
          minify: false,
          sourcemap: false,
          lib: {
            entry: path.join(rootDir, 'extension/content/injector.ts'),
            name: 'FormAssistInjector',
            formats: ['iife'],
            fileName: () => 'injector.js',
          },
          rollupOptions: {
            output: {
              inlineDynamicImports: true,
            },
          },
        },
      });

      // Clean up extra css files in content dir if generated by lib build
      const contentFiles = fs.readdirSync(contentOutDir);
      contentFiles.forEach((file) => {
        if (file.endsWith('.css')) {
          fs.rmSync(path.join(contentOutDir, file), { force: true });
        }
      });

      // 3. Bundle fonts as woff2 in dist-extension/fonts/
      const fontsDir = path.join(distExtensionDir, 'fonts');
      fs.mkdirSync(fontsDir, { recursive: true });

      const muktaDir = path.join(rootDir, 'node_modules/@fontsource/mukta/files');
      const balooDir = path.join(rootDir, 'node_modules/@fontsource/baloo-2/files');

      [muktaDir, balooDir].forEach((dir) => {
        if (fs.existsSync(dir)) {
          const files = fs.readdirSync(dir);
          files.forEach((f) => {
            if (f.endsWith('.woff2')) {
              fs.copyFileSync(path.join(dir, f), path.join(fontsDir, f));
            }
          });
        }
      });

      // 4. Generate compliant manifest.json (NFR-PRIV.1, NFR-PRIV.2)
      const backendUrl = process.env.VITE_SUPABASE_URL || '';
      let hostPermissions = ['https://*.supabase.co/*', 'http://localhost:3000/*'];
      if (backendUrl) {
        try {
          const origin = new URL(backendUrl).origin;
          hostPermissions = [`${origin}/*`];
        } catch {
          // fallback
        }
      }

      const manifestContent = {
        manifest_version: 3,
        name: 'FormAssist — Smart Civic & Banking Form Assistant',
        version: '1.0.0',
        description:
          'Multilingual assistive browser overlay for complex digital forms with privacy-first guidance and fraud risk detection.',
        permissions: ['activeTab', 'scripting', 'storage'],
        host_permissions: hostPermissions,
        action: {
          default_popup: 'popup.html',
          default_title: 'FormAssist Assistant',
          default_icon: {
            '16': 'icons/icon-16.png',
            '48': 'icons/icon-48.png',
            '128': 'icons/icon-128.png',
          },
        },
        options_ui: {
          page: 'options.html',
          open_in_tab: true,
        },
        background: {
          service_worker: 'background/service-worker.js',
          type: 'module',
        },
        web_accessible_resources: [
          {
            resources: ['fonts/*.woff2', 'assets/*.woff2'],
            matches: ['<all_urls>'],
            use_dynamic_url: true,
          },
        ],
        icons: {
          '16': 'icons/icon-16.png',
          '48': 'icons/icon-48.png',
          '128': 'icons/icon-128.png',
        },
      };

      fs.writeFileSync(
        path.join(distExtensionDir, 'manifest.json'),
        JSON.stringify(manifestContent, null, 2)
      );

      // Copy icons
      const iconsSrc = path.join(rootDir, 'extension/icons');
      const iconsDest = path.join(distExtensionDir, 'icons');
      if (fs.existsSync(iconsSrc)) {
        fs.cpSync(iconsSrc, iconsDest, { recursive: true });
      }

      // Ensure popup.html, options.html, onboarding.html exist at root of dist-extension
      ['popup.html', 'options.html', 'onboarding.html'].forEach((htmlFile) => {
        const srcInExt = path.join(distExtensionDir, 'extension', htmlFile);
        const destInRoot = path.join(distExtensionDir, htmlFile);
        if (fs.existsSync(srcInExt)) {
          fs.copyFileSync(srcInExt, destInRoot);
        }
      });

      // Also ensure popup/index.html compatibility
      const popupDir = path.join(distExtensionDir, 'popup');
      fs.mkdirSync(popupDir, { recursive: true });
      if (fs.existsSync(path.join(distExtensionDir, 'popup.html'))) {
        fs.copyFileSync(
          path.join(distExtensionDir, 'popup.html'),
          path.join(popupDir, 'index.html')
        );
      }

      console.log('✅ FormAssist extension build completed in dist-extension/');
    },
  };
}

export default defineConfig({
  plugins: [react(), tailwindcss(), manifestV3Plugin()],
  resolve: {
    alias: {
      '@': rootDir,
    },
  },
  build: {
    outDir: 'dist-extension',
    emptyOutDir: true,
    rollupOptions: {
      input: {
        popup: path.resolve(rootDir, 'extension/popup.html'),
        options: path.resolve(rootDir, 'extension/options.html'),
        onboarding: path.resolve(rootDir, 'extension/onboarding.html'),
      },
    },
  },
});
